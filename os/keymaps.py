"""Generate Pithos CORE keyboard layouts from the XKB data through ckbcomp.

Each layout maps PS/2 set 1 scancodes 0..127 in four levels (plain, Shift, AltGr,
Shift+AltGr) to BMP codepoints. Dead keys are 0xF000 + their accent index; letters that
Caps Lock affects are flagged per key. Dead key compositions come from Unicode NFC.
The output is a NASM include; ckbcomp is needed only to regenerate it.
"""
import argparse
import re
import subprocess
import unicodedata
from pathlib import Path

LAYOUTS = [("us", "us"), ("uk", "gb"), ("it", "it"), ("de", "de"), ("fr", "fr"), ("es", "es"),
           ("pt", "pt"), ("br", "br"), ("ch", "ch"), ("se", "se"), ("fi", "fi"), ("no", "no"), ("dk", "dk")]
# Dead keys: XKB name, combining mark, spacing form.
DEAD = [("grave", 0x300, "`"), ("acute", 0x301, "´"), ("circumflex", 0x302, "^"), ("tilde", 0x303, "~"),
        ("macron", 0x304, "¯"), ("breve", 0x306, "˘"), ("abovedot", 0x307, "˙"),
        ("diaeresis", 0x308, "¨"), ("abovering", 0x30a, "˚"), ("doubleacute", 0x30b, "˝"),
        ("caron", 0x30c, "ˇ"), ("cedilla", 0x327, "¸"), ("ogonek", 0x328, "˛")]
ALIASES = {"kdoubleacute": "doubleacute", "kbreve": "breve"}


def parse(layout):
    text = subprocess.run(["ckbcomp", "-compact", layout], capture_output=True, text=True, check=True).stdout
    table = [[0] * 4 for _ in range(128)]
    caps = [0] * 128
    for line in text.splitlines():
        match = re.match(r"keycode\s+(\d+)\s*=\s*(.*)", line)
        if not match or int(match.group(1)) >= 128:
            continue
        code, symbols = int(match.group(1)), match.group(2).split()
        for level in range(4):
            if level >= len(symbols):
                break
            symbol = symbols[level]
            if symbol.startswith("+"):
                symbol = symbol[1:]
                if level == 0:
                    caps[code] = 1
            if symbol.startswith("U+"):
                value = int(symbol[2:], 16)
                table[code][level] = value if 0x20 <= value < 0xf000 and value != 0x7f else 0
            elif symbol.startswith("dead_"):
                name = ALIASES.get(symbol[5:], symbol[5:])
                names = [dead[0] for dead in DEAD]
                table[code][level] = 0xf000 + names.index(name) if name in names else 0
    # Levels without their own symbol repeat the lower level, as on the console.
    for row in table:
        if not row[1]:
            row[1] = row[0]
        if not row[3]:
            row[3] = row[2]
    return table, caps


def compositions():
    pairs = []
    for index, (_, mark, spacing) in enumerate(DEAD):
        pairs.append((index, 0x20, ord(spacing)))
        for base in range(0x41, 0x17f):
            char = chr(base)
            if not char.isalpha():
                continue
            composed = unicodedata.normalize("NFC", char + chr(mark))
            if len(composed) == 1:
                pairs.append((index, base, ord(composed)))
    return pairs


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    lines = ["; Generated by os/keymaps.py from XKB through ckbcomp. Do not edit.",
             f"%define KEYMAP_COUNT {len(LAYOUTS)}",
             f"%define KEYMAP_BYTES {128 * 4 * 2 + 128}", "section .rodata", "keymap_names:"]
    lines += [f'    db "{name}",0,0,0' for name, _ in LAYOUTS]
    lines.append("align 2")
    lines.append("keymaps:")
    for name, layout in LAYOUTS:
        table, caps = parse(layout)
        lines.append(f"; {name}: XKB layout {layout}")
        for start in range(0, 128, 8):
            lines.append("    dw " + ",".join(f"0x{value:04x}" for row in table[start:start + 8] for value in row))
        lines.append("    db " + ",".join(map(str, caps)))
    pairs = compositions()
    lines.append(f"%define DEAD_PAIRS {len(pairs)}")
    lines.append("dead_spacing:")
    lines.append("    dw " + ",".join(f"0x{ord(spacing):04x}" for _, _, spacing in DEAD))
    lines.append("dead_pairs:                 ; dead index, base, composed")
    for start in range(0, len(pairs), 6):
        lines.append("    dw " + ",".join(f"{d},0x{b:04x},0x{c:04x}" for d, b, c in pairs[start:start + 6]))
    lines.append("section .text")
    args.output.write_text("\n".join(lines) + "\n", encoding="ascii")
    print(f"Keyboard layouts: {', '.join(name for name, _ in LAYOUTS)}; {len(pairs)} dead key compositions")


if __name__ == "__main__":
    main()
